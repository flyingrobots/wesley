#!/usr/bin/env node
/**
 * SHA-lock HOLMES CLI - Sidecar intelligence for Wesley
 */

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { Command } from 'commander';
import {
  GENERATED_ARTIFACT_DIR,
  GENERATED_BUNDLE_PATH,
  generatedArtifactPathCandidates
} from '@wesley/core';
import { Holmes } from './Holmes.mjs';
import { Watson } from './Watson.mjs';
import {
  attachCommandRun,
  formatCommandRunFailureLabel,
  formatCommandRunMarkdown,
  HOLMES_COMMAND_TRANSMUTATIONS,
  withCommandRun
} from './command-run.mjs';
import {
  inspectPersistedRuntimeRun,
  listPersistedRuntimeRuns
} from './runtime-run.mjs';
import { readWeightConfig } from './weight-config.mjs';
import { HOLMES_WEIGHT_CONFIG_PATH } from './config-paths.mjs';
import { buildMoriartyPrediction, resolveMoriartyExecutionPaths } from './moriarty-predict-workflow.mjs';
import {
  holmesReportSchema,
  watsonReportSchema,
  validateReport
} from './report-schemas.mjs';

function resolvePath(target, fallback) {
  const chosen = target || fallback;
  return path.isAbsolute(chosen) ? chosen : path.resolve(chosen);
}

function loadBundle(bundlePath) {
  const resolved = resolvePath(bundlePath, path.resolve(GENERATED_BUNDLE_PATH));
  for (const candidate of generatedArtifactPathCandidates(resolved)) {
    try {
      return JSON.parse(readFileSync(candidate, 'utf8'));
    } catch (error) {
      if (error?.code !== 'ENOENT') {
        throw new Error(`Unable to read Wesley bundle at ${candidate}`);
      }
    }
  }
  throw new Error(`No Wesley bundle found at ${resolved}. Run "wesley generate --emit-bundle" first.`);
}

function ensureValidReport(label, schema, data) {
  const { valid, errors } = validateReport(schema, data);
  if (!valid) {
    const detail = errors.map(err => ` - ${err}`).join('\n');
    throw new Error(`[${label}] report validation failed:\n${detail}`);
  }
}

async function main() {
  const program = new Command();

  program
    .name('holmes')
    .description('SHA-lock HOLMES - Wesley Schema Intelligence')
    .addHelpText('before', '\nSHA-lock HOLMES - Wesley Schema Intelligence\n')
    .showHelpAfterError()
    .option('--bundle-dir <path>', 'Path to Wesley generated artifact directory', GENERATED_ARTIFACT_DIR)
    .option('--history-file <path>', 'Path to MORIARTY history file')
    .addHelpText('after', `
Requires:
  .wesley-cache/bundle.json   Generated by: wesley generate --emit-bundle
  .wesley-cache/history.json  Built over time by multiple generations

"When you have eliminated the impossible, whatever remains,
 however improbable, must be the deployable."`);

  const runsCommand = program
    .command('runs')
    .description('Inspect persisted HOLMES and MORIARTY command runs');

  runsCommand
    .command('status')
    .description('List persisted HOLMES-family runtime runs from the ledger')
    .option('--transmutation <name>', `Filter runs by transmutation name (${HOLMES_COMMAND_TRANSMUTATIONS.join(', ')})`)
    .option('--status <state>', 'Filter runs by status: pending|running|completed|failed|cancelled')
    .option('--limit <n>', 'Maximum number of runs to return', '20')
    .option('--all', 'Show all persisted runs instead of Holmes-family runs only')
    .option('--json', 'Emit JSON')
    .action(async options => {
      const payload = await listPersistedRuntimeRuns({
        repoRoot: process.cwd(),
        transmutation: normalizeOptionalString(options.transmutation),
        status: normalizeOptionalString(options.status),
        limit: parseLimit(options.limit, 20),
        includeAll: Boolean(options.all)
      });

      if (options.json) {
        console.log(JSON.stringify(payload, null, 2));
        return;
      }

      if (payload.runs.length === 0) {
        console.log('No persisted Holmes-family runs found.');
        return;
      }

      console.log(`Persisted runs: ${payload.count}`);
      for (const run of payload.runs) {
        console.log(
          `${run.runId}  ${run.transmutation || 'n/a'}  ${run.command || 'n/a'}  ${run.status}  events=${run.eventCount} artifacts=${run.artifactCount}`
        );
        if (run.lastEventAt) {
          console.log(`  last=${run.lastEventAt} stream=${run.streamId}`);
        }
        if (run.failure?.code) {
          console.log(`  failure=${run.failure.code}${run.failure.message ? ` ${run.failure.message}` : ''}`);
        }
      }
    });

  runsCommand
    .command('inspect')
    .description('Inspect one persisted runtime run from the shared ledger')
    .requiredOption('--run-id <id>', 'Run ID to inspect')
    .option('--transmutation <name>', 'Transmutation name for direct stream lookup')
    .option('--json', 'Emit JSON')
    .action(async options => {
      const payload = await inspectPersistedRuntimeRun({
        repoRoot: process.cwd(),
        runId: String(options.runId || '').trim(),
        transmutation: normalizeOptionalString(options.transmutation)
      });

      if (options.json) {
        console.log(JSON.stringify(payload, null, 2));
        return;
      }

      console.log(`Run: ${payload.run.runId}`);
      console.log(`Transmutation: ${payload.run.transmutation}`);
      console.log(`Command: ${payload.run.command || 'n/a'}`);
      console.log(`Status: ${payload.run.status}`);
      console.log(`Stream: ${payload.run.streamId}`);
      console.log(`Events: ${payload.run.eventCount}`);
      console.log(`Artifacts: ${payload.run.artifactCount}`);
      console.log(`Ledger: ${payload.ledgerDir}`);
      console.log(`Snapshot: ${payload.snapshot ? `yes (seq=${payload.snapshot.lastSequence})` : 'no'}`);
      if (payload.run.startedAt) console.log(`Started: ${payload.run.startedAt}`);
      if (payload.run.completedAt) console.log(`Completed: ${payload.run.completedAt}`);
      if (payload.run.failure?.code) {
        console.log(`Failure: ${payload.run.failure.code}${payload.run.failure.message ? ` - ${payload.run.failure.message}` : ''}`);
      }
    });

  program
    .command('investigate')
    .description('Run HOLMES investigation on Wesley generated artifacts')
    .option('--json <file>', 'Write investigation JSON to file')
    .action(async options => {
      const opts = program.optsWithGlobals();
      const bundleDir = resolvePath(opts.bundleDir, GENERATED_ARTIFACT_DIR);
      const execution = await withCommandRun({
        repoRoot: path.resolve(bundleDir, '..'),
        command: 'investigate',
        sources: {
          bundleDir,
          bundlePath: path.join(bundleDir, 'bundle.json')
        },
        task: async () => {
          const bundle = loadBundle(path.join(bundleDir, 'bundle.json'));
          const holmes = new Holmes(bundle);
          const data = holmes.investigationData();
          ensureValidReport('HOLMES', holmesReportSchema, data);
          return {
            data,
            output: holmes.renderInvestigation(data)
          };
        }
      });
      attachCommandRun(execution.data, execution.commandRun);
      if (options.json) {
        writeFileSync(options.json, JSON.stringify(execution.data, null, 2));
      }
      console.log(execution.output);
      console.log('');
      console.log(formatCommandRunMarkdown(execution.commandRun));
    });

  program
    .command('verify')
    .description('Run WATSON verification')
    .option('--json <file>', 'Write verification JSON to file')
    .action(async options => {
      const opts = program.optsWithGlobals();
      const bundleDir = resolvePath(opts.bundleDir, GENERATED_ARTIFACT_DIR);
      const execution = await withCommandRun({
        repoRoot: path.resolve(bundleDir, '..'),
        command: 'verify',
        sources: {
          bundleDir,
          bundlePath: path.join(bundleDir, 'bundle.json')
        },
        task: async () => {
          const bundle = loadBundle(path.join(bundleDir, 'bundle.json'));
          const watson = new Watson(bundle);
          const data = watson.verificationData();
          ensureValidReport('WATSON', watsonReportSchema, data);
          return {
            data,
            output: watson.renderVerification(data)
          };
        }
      });
      attachCommandRun(execution.data, execution.commandRun);
      if (options.json) {
        writeFileSync(options.json, JSON.stringify(execution.data, null, 2));
      }
      console.log(execution.output);
      console.log('');
      console.log(formatCommandRunMarkdown(execution.commandRun));
    });

  program
    .command('predict')
    .description('Run MORIARTY predictions')
    .option('--json <file>', 'Write prediction JSON to file')
    .option('--run-id <id>', 'Bind prediction context to a persisted Wesley run')
    .option('--transmutation <name>', 'Disambiguate the persisted run stream by transmutation')
    .option('--counterfactual [baseRef]', 'Analyze a module-provided counterfactual lane against a base ref')
    .option('--counterfactual-braid <ref>', 'Add a braid ref to the counterfactual lane', collectRepeatableOption, [])
    .option('--explain', 'Show resolved refs, digests, and counterfactual details')
    .action(async options => {
      const opts = program.optsWithGlobals();
      const paths = resolveMoriartyExecutionPaths({
        bundleDir: opts.bundleDir,
        historyFile: opts.historyFile
      });
      const bundleDir = paths.bundleDir;
      const execution = await withCommandRun({
        repoRoot: paths.repoRoot,
        command: 'predict',
        sources: {
          bundleDir,
          historyFile: paths.historyFile,
          requestedRunId: options.runId || null,
          requestedTransmutation: options.transmutation || null,
          counterfactual: typeof options.counterfactual !== 'undefined',
          braidCount: Array.isArray(options.counterfactualBraid) ? options.counterfactualBraid.length : 0
        },
        task: async () => buildMoriartyPrediction({
          bundleDir: paths.bundleDir,
          historyFile: paths.historyFile,
          runId: options.runId,
          transmutation: options.transmutation,
          counterfactual: options.counterfactual,
          braidRefs: options.counterfactualBraid,
          explain: Boolean(options.explain),
          env: process.env
        })
      });
      attachCommandRun(execution.data, execution.commandRun);
      if (options.json) {
        writeFileSync(options.json, JSON.stringify(execution.data, null, 2));
      }
      console.log(execution.output);
      console.log('');
      console.log(formatCommandRunMarkdown(execution.commandRun));
    });

  program
    .command('report')
    .description('Generate combined HOLMES, WATSON, and MORIARTY report')
    .option('--json <file>', 'Write combined JSON to file')
    .option('--run-id <id>', 'Bind MORIARTY context to a persisted Wesley run')
    .option('--transmutation <name>', 'Disambiguate the persisted run stream by transmutation')
    .option('--counterfactual [baseRef]', 'Analyze a module-provided counterfactual lane against a base ref')
    .option('--counterfactual-braid <ref>', 'Add a braid ref to the counterfactual lane', collectRepeatableOption, [])
    .option('--explain', 'Show resolved refs, digests, and counterfactual details')
    .action(async options => {
      const opts = program.optsWithGlobals();
      const paths = resolveMoriartyExecutionPaths({
        bundleDir: opts.bundleDir,
        historyFile: opts.historyFile
      });
      const bundleDir = paths.bundleDir;
      const execution = await withCommandRun({
        repoRoot: paths.repoRoot,
        command: 'report',
        sources: {
          bundleDir,
          bundlePath: path.join(bundleDir, 'bundle.json'),
          historyFile: paths.historyFile,
          requestedRunId: options.runId || null,
          requestedTransmutation: options.transmutation || null,
          counterfactual: typeof options.counterfactual !== 'undefined',
          braidCount: Array.isArray(options.counterfactualBraid) ? options.counterfactualBraid.length : 0
        },
        task: async () => {
          const bundle = loadBundle(path.join(bundleDir, 'bundle.json'));
          const holmes = new Holmes(bundle);
          const watson = new Watson(bundle);
          const holmesData = holmes.investigationData();
          const watsonData = watson.verificationData();
          const moriartyResult = await buildMoriartyPrediction({
            bundleDir: paths.bundleDir,
            historyFile: paths.historyFile,
            runId: options.runId,
            transmutation: options.transmutation,
            counterfactual: options.counterfactual,
            braidRefs: options.counterfactualBraid,
            explain: Boolean(options.explain),
            env: process.env
          });
          const moriartyData = moriartyResult.data;

          ensureValidReport('HOLMES', holmesReportSchema, holmesData);
          ensureValidReport('WATSON', watsonReportSchema, watsonData);

          return {
            data: {
              holmes: holmesData,
              watson: watsonData,
              moriarty: moriartyData
            },
            output: [
              '# The Case of Schema Investigation',
              '',
              holmes.renderInvestigation(holmesData),
              '',
              '---',
              '',
              watson.renderVerification(watsonData),
              '',
              '---',
              '',
              moriartyResult.output
            ].join('\n')
          };
        }
      });
      if (options.json) {
        writeFileSync(options.json, JSON.stringify({
          ...execution.data,
          commandRun: execution.commandRun
        }, null, 2));
      }

      console.log(execution.output);
      console.log('');
      console.log(formatCommandRunMarkdown(execution.commandRun));
    });

  program
    .command('weights')
    .aliases(['weights:validate', 'weights-validate'])
    .description(`Validate ${HOLMES_WEIGHT_CONFIG_PATH} structure`)
    .argument('[target]', 'Path to weights configuration')
    .option('-f, --file <file>', 'Path to weights configuration')
    .option('--json <file>', 'Write weights JSON to file')
    .action((targetArg, options) => {
      const target = options.file || targetArg || HOLMES_WEIGHT_CONFIG_PATH;
      try {
        const { config } = readWeightConfig(target, { required: true });

        console.log('weights configuration valid');
        if (options.json) {
          writeFileSync(options.json, JSON.stringify(config, null, 2));
        }
      } catch (error) {
        throw new Error(`Weight configuration invalid: ${error?.message ?? 'unknown error'}`);
      }
    });

  await program.parseAsync(process.argv);
}

function collectRepeatableOption(value, previous = []) {
  previous.push(value);
  return previous;
}

function parseLimit(value, fallback = 20) {
  const parsed = Number.parseInt(String(value || ''), 10);
  return Number.isFinite(parsed) && parsed >= 0 ? parsed : fallback;
}

function normalizeOptionalString(value) {
  return typeof value === 'string' && value.trim() ? value.trim() : null;
}

main().catch(error => {
  console.error(`Investigation failed${formatCommandRunFailureLabel(error)}:`, error.message);
  process.exit(1);
});
