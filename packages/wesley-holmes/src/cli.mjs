#!/usr/bin/env node
/**
 * SHA-lock HOLMES CLI - Sidecar intelligence for Wesley
 */

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { Command } from 'commander';
import {
  GENERATED_ARTIFACT_DIR,
  GENERATED_BUNDLE_PATH,
  generatedArtifactPathCandidates
} from '@wesley/core';
import { Holmes } from './Holmes.mjs';
import { Watson } from './Watson.mjs';
import { Moriarty } from './Moriarty.mjs';
import { attachRuntimeRun, loadRuntimeRunRecord } from './runtime-run.mjs';
import { readWeightConfig } from './weight-config.mjs';
import { HOLMES_WEIGHT_CONFIG_PATH } from './config-paths.mjs';
import {
  analyzeCounterfactual,
  loadHolmesCounterfactualPolicy,
  resolveCounterfactualLaneRequest
} from './index.mjs';
import {
  holmesReportSchema,
  watsonReportSchema,
  moriartyReportSchema,
  validateReport
} from './report-schemas.mjs';

function resolvePath(target, fallback) {
  const chosen = target || fallback;
  return path.isAbsolute(chosen) ? chosen : path.resolve(chosen);
}

function loadBundle(bundlePath) {
  const resolved = resolvePath(bundlePath, path.resolve(GENERATED_BUNDLE_PATH));
  for (const candidate of generatedArtifactPathCandidates(resolved)) {
    try {
      return JSON.parse(readFileSync(candidate, 'utf8'));
    } catch (error) {
      if (error?.code !== 'ENOENT') {
        throw new Error(`Unable to read Wesley bundle at ${candidate}`);
      }
    }
  }
  throw new Error(`No Wesley bundle found at ${resolved}. Run "wesley generate --emit-bundle" first.`);
}

function loadHistory(historyPath, bundleDir) {
  const defaultHistory = path.join(bundleDir ?? GENERATED_ARTIFACT_DIR, 'history.json');
  const resolved = resolvePath(historyPath, path.resolve(defaultHistory));
  for (const candidate of generatedArtifactPathCandidates(resolved)) {
    try {
      return JSON.parse(readFileSync(candidate, 'utf8'));
    } catch {
      continue;
    }
  }
  return { points: [] };
}

function loadMoriartyContext(bundleDir) {
  try {
    const contextPath = resolvePath(null, path.join(bundleDir ?? GENERATED_ARTIFACT_DIR, 'moriarty-context.json'));
    return JSON.parse(readFileSync(contextPath, 'utf8'));
  } catch {
    return {};
  }
}

function ensureValidReport(label, schema, data) {
  const { valid, errors } = validateReport(schema, data);
  if (!valid) {
    const detail = errors.map(err => ` - ${err}`).join('\n');
    throw new Error(`[${label}] report validation failed:\n${detail}`);
  }
}

async function attachCounterfactual(data, {
  bundleDir,
  outDir,
  schemaPath,
  transmutation,
  baseRef,
  braidRefs = [],
  explain = false
}) {
  const repoRoot = path.resolve(bundleDir, '..');
  const policy = await loadHolmesCounterfactualPolicy({ repoRoot, env: process.env });
  const lane = resolveCounterfactualLaneRequest({
    policy,
    baseRef,
    braidRefs
  });
  const counterfactual = await analyzeCounterfactual({
    repoRoot,
    lane,
    includeTransferPlan: true,
    policy,
    surface: {
      bundleDir,
      outDir,
      schemaPath,
      transmutation
    }
  });
  data.counterfactual = explain
    ? counterfactual
    : { ...counterfactual };
  data.warnings = Array.isArray(data.warnings) ? data.warnings : [];
  if (typeof data.confidence === 'number' && Number.isFinite(counterfactual?.judgment?.confidenceAdjustment)) {
    data.confidence = Math.max(0, Math.min(100, data.confidence + counterfactual.judgment.confidenceAdjustment));
  }
  if (counterfactual?.judgment?.status && counterfactual.judgment.status !== 'clean') {
    data.patterns = Array.isArray(data.patterns) ? data.patterns : [];
    data.patterns.push({
      type: 'COUNTERFACTUAL_ISSUE',
      description: counterfactual.judgment.reasons.join(' ')
    });
  }
}

async function attachRuntime(data, {
  bundleDir,
  runId,
  transmutation
}) {
  if (typeof runId !== 'string' || !runId.trim()) {
    return null;
  }

  const runtimeRecord = await loadRuntimeRunRecord({
    repoRoot: path.resolve(bundleDir, '..'),
    runId,
    transmutation
  });
  attachRuntimeRun(data, runtimeRecord);
  return runtimeRecord;
}

async function main() {
  const program = new Command();

  program
    .name('holmes')
    .description('SHA-lock HOLMES - Wesley Schema Intelligence')
    .addHelpText('before', '\nSHA-lock HOLMES - Wesley Schema Intelligence\n')
    .showHelpAfterError()
    .option('--bundle-dir <path>', 'Path to Wesley generated artifact directory', GENERATED_ARTIFACT_DIR)
    .option('--history-file <path>', 'Path to MORIARTY history file')
    .addHelpText('after', `
Requires:
  .wesley-cache/bundle.json   Generated by: wesley generate --emit-bundle
  .wesley-cache/history.json  Built over time by multiple generations

"When you have eliminated the impossible, whatever remains,
 however improbable, must be the deployable."`);

  program
    .command('investigate')
    .description('Run HOLMES investigation on Wesley generated artifacts')
    .option('--json <file>', 'Write investigation JSON to file')
    .action(options => {
      const opts = program.optsWithGlobals();
      const bundlePath = path.join(resolvePath(opts.bundleDir, GENERATED_ARTIFACT_DIR), 'bundle.json');
      const bundle = loadBundle(bundlePath);
      const holmes = new Holmes(bundle);
      const data = holmes.investigationData();
      ensureValidReport('HOLMES', holmesReportSchema, data);
      if (options.json) {
        writeFileSync(options.json, JSON.stringify(data, null, 2));
      }
      console.log(holmes.renderInvestigation(data));
    });

  program
    .command('verify')
    .description('Run WATSON verification')
    .option('--json <file>', 'Write verification JSON to file')
    .action(options => {
      const opts = program.optsWithGlobals();
      const bundlePath = path.join(resolvePath(opts.bundleDir, GENERATED_ARTIFACT_DIR), 'bundle.json');
      const bundle = loadBundle(bundlePath);
      const watson = new Watson(bundle);
      const data = watson.verificationData();
      ensureValidReport('WATSON', watsonReportSchema, data);
      if (options.json) {
        writeFileSync(options.json, JSON.stringify(data, null, 2));
      }
      console.log(watson.renderVerification(data));
    });

  program
    .command('predict')
    .description('Run MORIARTY predictions')
    .option('--json <file>', 'Write prediction JSON to file')
    .option('--run-id <id>', 'Bind prediction context to a persisted Wesley run')
    .option('--transmutation <name>', 'Disambiguate the persisted run stream by transmutation')
    .option('--counterfactual [baseRef]', 'Analyze a git-warp counterfactual lane against a base ref')
    .option('--explain', 'Show resolved refs, digests, and counterfactual details')
    .action(async options => {
      const opts = program.optsWithGlobals();
      const bundleDir = resolvePath(opts.bundleDir, GENERATED_ARTIFACT_DIR);
      const history = loadHistory(opts.historyFile, bundleDir);
      const ctx = loadMoriartyContext(bundleDir);
      const moriarty = new Moriarty(history, ctx);
      const data = moriarty.predictionData();
      const runtime = await attachRuntime(data, {
        bundleDir,
        runId: options.runId,
        transmutation: options.transmutation
      });
      if (typeof options.counterfactual !== 'undefined') {
        const baseRef = typeof options.counterfactual === 'string' && options.counterfactual.length > 0
          ? options.counterfactual
          : (process.env.MORIARTY_BASE_REF || process.env.GITHUB_BASE_REF || 'main');
        await attachCounterfactual(data, {
          bundleDir,
          outDir: path.resolve(path.dirname(bundleDir), 'out'),
          schemaPath: path.resolve(path.dirname(bundleDir), 'schema.graphql'),
          transmutation: runtime?.run?.transmutation || options.transmutation,
          baseRef,
          explain: Boolean(options.explain)
        });
      }
      ensureValidReport('MORIARTY', moriartyReportSchema, data);
      if (options.json) {
        writeFileSync(options.json, JSON.stringify(data, null, 2));
      }
      console.log(moriarty.renderPrediction(data));
    });

  program
    .command('report')
    .description('Generate combined HOLMES, WATSON, and MORIARTY report')
    .option('--json <file>', 'Write combined JSON to file')
    .option('--run-id <id>', 'Bind MORIARTY context to a persisted Wesley run')
    .option('--transmutation <name>', 'Disambiguate the persisted run stream by transmutation')
    .option('--counterfactual [baseRef]', 'Analyze a git-warp counterfactual lane against a base ref')
    .option('--explain', 'Show resolved refs, digests, and counterfactual details')
    .action(async options => {
      const opts = program.optsWithGlobals();
      const bundleDir = resolvePath(opts.bundleDir, GENERATED_ARTIFACT_DIR);
      const bundlePath = path.join(bundleDir, 'bundle.json');
      const bundle = loadBundle(bundlePath);
      const history = loadHistory(opts.historyFile, bundleDir);
      const ctx = loadMoriartyContext(bundleDir);
      const holmes = new Holmes(bundle);
      const watson = new Watson(bundle);
      const moriarty = new Moriarty(history, ctx);
      const holmesData = holmes.investigationData();
      const watsonData = watson.verificationData();
      const moriartyData = moriarty.predictionData();
      const runtime = await attachRuntime(moriartyData, {
        bundleDir,
        runId: options.runId,
        transmutation: options.transmutation
      });
      if (typeof options.counterfactual !== 'undefined') {
        const baseRef = typeof options.counterfactual === 'string' && options.counterfactual.length > 0
          ? options.counterfactual
          : (process.env.MORIARTY_BASE_REF || process.env.GITHUB_BASE_REF || 'main');
        await attachCounterfactual(moriartyData, {
          bundleDir,
          outDir: path.resolve(path.dirname(bundleDir), 'out'),
          schemaPath: path.resolve(path.dirname(bundleDir), 'schema.graphql'),
          transmutation: runtime?.run?.transmutation || options.transmutation,
          baseRef,
          explain: Boolean(options.explain)
        });
      }

      ensureValidReport('HOLMES', holmesReportSchema, holmesData);
      ensureValidReport('WATSON', watsonReportSchema, watsonData);
      ensureValidReport('MORIARTY', moriartyReportSchema, moriartyData);

      if (options.json) {
        writeFileSync(options.json, JSON.stringify({
          holmes: holmesData,
          watson: watsonData,
          moriarty: moriartyData
        }, null, 2));
      }

      console.log('# The Case of Schema Investigation\n');
      console.log(holmes.renderInvestigation(holmesData));
      console.log('\n---\n');
      console.log(watson.renderVerification(watsonData));
      console.log('\n---\n');
      console.log(moriarty.renderPrediction(moriartyData));
    });

  program
    .command('weights')
    .aliases(['weights:validate', 'weights-validate'])
    .description(`Validate ${HOLMES_WEIGHT_CONFIG_PATH} structure`)
    .argument('[target]', 'Path to weights configuration')
    .option('-f, --file <file>', 'Path to weights configuration')
    .option('--json <file>', 'Write weights JSON to file')
    .action((targetArg, options) => {
      const target = options.file || targetArg || HOLMES_WEIGHT_CONFIG_PATH;
      try {
        const { config } = readWeightConfig(target, { required: true });

        console.log('weights configuration valid');
        if (options.json) {
          writeFileSync(options.json, JSON.stringify(config, null, 2));
        }
      } catch (error) {
        throw new Error(`Weight configuration invalid: ${error?.message ?? 'unknown error'}`);
      }
    });

  await program.parseAsync(process.argv);
}

main().catch(error => {
  console.error('Investigation failed:', error.message);
  process.exit(1);
});
