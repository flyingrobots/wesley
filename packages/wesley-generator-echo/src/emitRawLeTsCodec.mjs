/**
 * Emit a TypeScript `raw_le_codec.generated.ts` file containing deterministic
 * encode/decode functions for every OBJECT and ENUM type in the IR.
 *
 * Layout follows SPEC-0008 (byte-identical to the Rust raw_le codec):
 * - Fields encoded in alphabetical order
 * - Little-endian byte order for all numerics
 * - Collision-free Option prefix (0x00 = None, 0x01 = Some)
 * - NaN canonicalization for f32 (0x7FC00000)
 *
 * Returns `null` when the IR contains no OBJECT or ENUM types.
 *
 * @param {{ types: Array<{ name: string, kind: string, fields?: Array<{ name: string, type: string, required: boolean, list: boolean }>, values?: string[] }> }} ir
 * @returns {string | null}
 */
export function emitRawLeTsCodec(ir) {
  const encodableTypes = (ir.types ?? []).filter(
    (t) => t.kind === 'OBJECT' || t.kind === 'ENUM',
  );

  if (encodableTypes.length === 0) return null;

  const lines = [];

  lines.push('// Auto-generated by @wesley/generator-echo — DO NOT EDIT');
  lines.push('');

  // Emit type interfaces/enums first
  for (const type of encodableTypes) {
    if (type.kind === 'ENUM') {
      emitEnumType(lines, type);
    } else if (type.kind === 'OBJECT') {
      emitObjectInterface(lines, type, encodableTypes);
    }
  }

  // Shared helpers
  emitHelpers(lines);

  // Per-type encode/decode functions
  for (const type of encodableTypes) {
    if (type.kind === 'ENUM') {
      emitEnumCodec(lines, type);
    } else if (type.kind === 'OBJECT') {
      emitObjectCodec(lines, type);
    }
  }

  return lines.join('\n');
}

// ---------------------------------------------------------------------------
// Type / Interface emission
// ---------------------------------------------------------------------------

function emitEnumType(lines, type) {
  const sorted = [...type.values].sort((a, b) => a < b ? -1 : a > b ? 1 : 0);
  lines.push(`export type ${type.name} = ${sorted.map((v) => `'${v}'`).join(' | ')};`);
  lines.push('');
}

function tsTypeForField(fieldType, required, list, encodableTypes) {
  let tsType;
  switch (fieldType) {
    case 'Boolean':
      tsType = 'boolean';
      break;
    case 'Int':
    case 'Float':
      tsType = 'number';
      break;
    case 'String':
    case 'ID':
      tsType = 'string';
      break;
    default: {
      // Could be an enum or object type
      tsType = fieldType;
      break;
    }
  }
  if (list) tsType = `${tsType}[]`;
  if (!required) tsType = `${tsType} | null | undefined`;
  return tsType;
}

function emitObjectInterface(lines, type, encodableTypes) {
  const fields = [...(type.fields ?? [])].sort((a, b) => a.name < b.name ? -1 : a.name > b.name ? 1 : 0);
  lines.push(`export interface ${type.name} {`);
  for (const field of fields) {
    const tsType = tsTypeForField(field.type, field.required, field.list, encodableTypes);
    const opt = field.required ? '' : '?';
    lines.push(`  ${field.name}${opt}: ${tsType};`);
  }
  lines.push('}');
  lines.push('');
}

// ---------------------------------------------------------------------------
// Shared encode/decode helpers
// ---------------------------------------------------------------------------

function emitHelpers(lines) {
  // TextEncoder singleton
  lines.push('const _textEncoder = new TextEncoder();');
  lines.push('const _textDecoder = new TextDecoder();');
  lines.push('');

  // _encodeBool
  lines.push('function _encodeBool(buf: number[], v: boolean): void {');
  lines.push('  buf.push(v ? 0x01 : 0x00);');
  lines.push('}');
  lines.push('');

  // _encodeI32
  lines.push('function _encodeI32(buf: number[], v: number): void {');
  lines.push('  const tmp = new DataView(new ArrayBuffer(4));');
  lines.push('  tmp.setInt32(0, v, true);');
  lines.push('  for (let i = 0; i < 4; i++) buf.push(tmp.getUint8(i));');
  lines.push('}');
  lines.push('');

  // _encodeF32
  lines.push('function _encodeF32(buf: number[], v: number): void {');
  lines.push('  const tmp = new DataView(new ArrayBuffer(4));');
  lines.push('  if (Number.isNaN(v)) {');
  lines.push('    tmp.setUint32(0, 0x7FC00000, true);');
  lines.push('  } else {');
  lines.push('    tmp.setFloat32(0, v, true);');
  lines.push('  }');
  lines.push('  for (let i = 0; i < 4; i++) buf.push(tmp.getUint8(i));');
  lines.push('}');
  lines.push('');

  // _encodeString
  lines.push('function _encodeString(buf: number[], v: string): void {');
  lines.push('  const encoded = _textEncoder.encode(v);');
  lines.push('  const tmp = new DataView(new ArrayBuffer(4));');
  lines.push('  tmp.setUint32(0, encoded.length, true);');
  lines.push('  for (let i = 0; i < 4; i++) buf.push(tmp.getUint8(i));');
  lines.push('  for (let i = 0; i < encoded.length; i++) buf.push(encoded[i]);');
  lines.push('}');
  lines.push('');

  // _encodeOption
  lines.push('function _encodeOption<T>(buf: number[], v: T | null | undefined, encodeInner: (buf: number[], v: T) => void): void {');
  lines.push('  if (v == null) {');
  lines.push('    buf.push(0x00);');
  lines.push('  } else {');
  lines.push('    buf.push(0x01);');
  lines.push('    encodeInner(buf, v);');
  lines.push('  }');
  lines.push('}');
  lines.push('');

  // _encodeList
  lines.push('function _encodeList<T>(buf: number[], v: T[], encodeInner: (buf: number[], v: T) => void): void {');
  lines.push('  const tmp = new DataView(new ArrayBuffer(4));');
  lines.push('  tmp.setUint32(0, v.length, true);');
  lines.push('  for (let i = 0; i < 4; i++) buf.push(tmp.getUint8(i));');
  lines.push('  for (const item of v) encodeInner(buf, item);');
  lines.push('}');
  lines.push('');

  // Decode helpers
  lines.push('function _decodeBool(bytes: Uint8Array, offset: { v: number }): boolean {');
  lines.push('  if (offset.v >= bytes.length) throw new Error("unexpected end of input");');
  lines.push('  const v = bytes[offset.v] !== 0x00;');
  lines.push('  offset.v += 1;');
  lines.push('  return v;');
  lines.push('}');
  lines.push('');

  lines.push('function _decodeI32(bytes: Uint8Array, offset: { v: number }): number {');
  lines.push('  if (offset.v + 4 > bytes.length) throw new Error("unexpected end of input");');
  lines.push('  const dv = new DataView(bytes.buffer, bytes.byteOffset + offset.v, 4);');
  lines.push('  const val = dv.getInt32(0, true);');
  lines.push('  offset.v += 4;');
  lines.push('  return val;');
  lines.push('}');
  lines.push('');

  lines.push('function _decodeF32(bytes: Uint8Array, offset: { v: number }): number {');
  lines.push('  if (offset.v + 4 > bytes.length) throw new Error("unexpected end of input");');
  lines.push('  const dv = new DataView(bytes.buffer, bytes.byteOffset + offset.v, 4);');
  lines.push('  const val = dv.getFloat32(0, true);');
  lines.push('  offset.v += 4;');
  lines.push('  return val;');
  lines.push('}');
  lines.push('');

  lines.push('function _decodeString(bytes: Uint8Array, offset: { v: number }): string {');
  lines.push('  if (offset.v + 4 > bytes.length) throw new Error("unexpected end of input");');
  lines.push('  const dv = new DataView(bytes.buffer, bytes.byteOffset + offset.v, 4);');
  lines.push('  const len = dv.getUint32(0, true);');
  lines.push('  offset.v += 4;');
  lines.push('  if (offset.v + len > bytes.length) throw new Error("unexpected end of input");');
  lines.push('  const val = _textDecoder.decode(bytes.subarray(offset.v, offset.v + len));');
  lines.push('  offset.v += len;');
  lines.push('  return val;');
  lines.push('}');
  lines.push('');

  lines.push('function _decodeOption<T>(bytes: Uint8Array, offset: { v: number }, decodeInner: (bytes: Uint8Array, offset: { v: number }) => T): T | null {');
  lines.push('  if (offset.v >= bytes.length) throw new Error("unexpected end of input");');
  lines.push('  const tag = bytes[offset.v];');
  lines.push('  offset.v += 1;');
  lines.push('  if (tag === 0x00) return null;');
  lines.push('  if (tag === 0x01) return decodeInner(bytes, offset);');
  lines.push('  throw new Error(`invalid option tag: ${tag}`);');
  lines.push('}');
  lines.push('');

  lines.push('function _decodeList<T>(bytes: Uint8Array, offset: { v: number }, decodeInner: (bytes: Uint8Array, offset: { v: number }) => T): T[] {');
  lines.push('  if (offset.v + 4 > bytes.length) throw new Error("unexpected end of input");');
  lines.push('  const dv = new DataView(bytes.buffer, bytes.byteOffset + offset.v, 4);');
  lines.push('  const count = dv.getUint32(0, true);');
  lines.push('  offset.v += 4;');
  lines.push('  const items: T[] = [];');
  lines.push('  for (let i = 0; i < count; i++) items.push(decodeInner(bytes, offset));');
  lines.push('  return items;');
  lines.push('}');
  lines.push('');
}

