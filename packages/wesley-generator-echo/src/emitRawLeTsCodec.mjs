const SCALAR_TYPES = new Set(['Boolean', 'Int', 'Float', 'String', 'ID']);

function isScalar(typeName) {
  return SCALAR_TYPES.has(typeName);
}

/**
 * Emit encode/decode for an ENUM type.
 * Variants sorted alphabetically; index is u32 LE.
 */
function emitEnumCodec(lines, type) {
  const sorted = [...type.values].sort((a, b) => a < b ? -1 : a > b ? 1 : 0);

  // encode
  lines.push(`export function encode${type.name}(value: ${type.name}): Uint8Array {`);
  lines.push('  const buf: number[] = [];');
  lines.push('  const tmp = new DataView(new ArrayBuffer(4));');
  lines.push('  let idx: number;');
  lines.push('  switch (value) {');
  sorted.forEach((v, i) => {
    lines.push(`    case '${v}': idx = ${i}; break;`);
  });
  lines.push(`    default: throw new Error('invalid enum variant: ' + value);`);
  lines.push('  }');
  lines.push('  tmp.setUint32(0, idx, true);');
  lines.push('  for (let i = 0; i < 4; i++) buf.push(tmp.getUint8(i));');
  lines.push('  return new Uint8Array(buf);');
  lines.push('}');
  lines.push('');

  // decode
  lines.push(`export function decode${type.name}(bytes: Uint8Array, offset?: number): { value: ${type.name}; bytesRead: number } {`);
  lines.push('  const off = { v: offset ?? 0 };');
  lines.push('  if (off.v + 4 > bytes.length) throw new Error("unexpected end of input");');
  lines.push('  const dv = new DataView(bytes.buffer, bytes.byteOffset + off.v, 4);');
  lines.push('  const idx = dv.getUint32(0, true);');
  lines.push('  off.v += 4;');
  lines.push('  let value: ' + type.name + ';');
  lines.push('  switch (idx) {');
  sorted.forEach((v, i) => {
    lines.push(`    case ${i}: value = '${v}'; break;`);
  });
  lines.push('    default: throw new Error("invalid enum variant: " + idx);');
  lines.push('  }');
  lines.push('  return { value, bytesRead: off.v - (offset ?? 0) };');
  lines.push('}');
  lines.push('');
}

/**
 * Emit encode/decode for an OBJECT type.
 * Fields sorted alphabetically.
 */
function emitObjectCodec(lines, type) {
  const fields = [...(type.fields ?? [])].sort((a, b) => a.name < b.name ? -1 : a.name > b.name ? 1 : 0);

  // In-place encode — appends directly to a shared buf (avoids intermediate Uint8Array alloc)
  lines.push(`function _encode${type.name}(buf: number[], value: ${type.name}): void {`);

  for (const field of fields) {
    emitFieldEncode(lines, field, `value.${field.name}`);
  }

  lines.push('}');
  lines.push('');

  // Public encode — returns Uint8Array
  lines.push(`export function encode${type.name}(value: ${type.name}): Uint8Array {`);
  lines.push('  const buf: number[] = [];');
  lines.push(`  _encode${type.name}(buf, value);`);
  lines.push('  return new Uint8Array(buf);');
  lines.push('}');
  lines.push('');

  // decode function
  lines.push(`export function decode${type.name}(bytes: Uint8Array, offset?: number): { value: ${type.name}; bytesRead: number } {`);
  lines.push('  const off = { v: offset ?? 0 };');

  for (const field of fields) {
    emitFieldDecode(lines, field);
  }

  lines.push(`  return {`);
  lines.push(`    value: { ${fields.map((f) => f.name).join(', ')} },`);
  lines.push(`    bytesRead: off.v - (offset ?? 0),`);
  lines.push(`  };`);
  lines.push('}');
  lines.push('');
}

// ---------------------------------------------------------------------------
// Field-level encode helpers
// ---------------------------------------------------------------------------

function encodeCallForScalar(typeName, accessor) {
  switch (typeName) {
    case 'Boolean':
      return `_encodeBool(buf, ${accessor});`;
    case 'Int':
      return `_encodeI32(buf, ${accessor});`;
    case 'Float':
      return `_encodeF32(buf, ${accessor});`;
    case 'String':
    case 'ID':
      return `_encodeString(buf, ${accessor});`;
    default:
      // Nested object — encode in-place, no intermediate allocation
      return `_encode${typeName}(buf, ${accessor});`;
  }
}

function encodeInnerClosureForType(typeName) {
  switch (typeName) {
    case 'Boolean':
      return '_encodeBool';
    case 'Int':
      return '_encodeI32';
    case 'Float':
      return '_encodeF32';
    case 'String':
    case 'ID':
      return '_encodeString';
    default:
      return `(buf, v) => _encode${typeName}(buf, v)`;
  }
}

function emitFieldEncode(lines, field, accessor) {
  const { type, required, list } = field;

  if (list && required) {
    lines.push(`  _encodeList(buf, ${accessor}, ${encodeInnerClosureForType(type)});`);
  } else if (list && !required) {
    lines.push(`  _encodeOption(buf, ${accessor}, (buf, inner) => _encodeList(buf, inner, ${encodeInnerClosureForType(type)}));`);
  } else if (!required) {
    lines.push(`  _encodeOption(buf, ${accessor}, ${encodeInnerClosureForType(type)});`);
  } else {
    lines.push(`  ${encodeCallForScalar(type, accessor)}`);
  }
}

// ---------------------------------------------------------------------------
// Field-level decode helpers
// ---------------------------------------------------------------------------

function decodeCallForType(typeName) {
  switch (typeName) {
    case 'Boolean':
      return '_decodeBool';
    case 'Int':
      return '_decodeI32';
    case 'Float':
      return '_decodeF32';
    case 'String':
    case 'ID':
      return '_decodeString';
    default:
      return `(bytes, off) => { const _r = decode${typeName}(bytes, off.v); off.v += _r.bytesRead; return _r.value; }`;
  }
}

function decodeDirectCallForType(typeName, fieldName) {
  switch (typeName) {
    case 'Boolean':
      return `const ${fieldName} = _decodeBool(bytes, off);`;
    case 'Int':
      return `const ${fieldName} = _decodeI32(bytes, off);`;
    case 'Float':
      return `const ${fieldName} = _decodeF32(bytes, off);`;
    case 'String':
    case 'ID':
      return `const ${fieldName} = _decodeString(bytes, off);`;
    default: {
      // Nested object — use its decode function, advance offset
      return `const _${fieldName}Res = decode${typeName}(bytes, off.v); const ${fieldName} = _${fieldName}Res.value; off.v += _${fieldName}Res.bytesRead;`;
    }
  }
}

function emitFieldDecode(lines, field) {
  const { name, type, required, list } = field;

  if (list && required) {
    lines.push(`  const ${name} = _decodeList(bytes, off, ${decodeCallForType(type)});`);
  } else if (list && !required) {
    lines.push(`  const ${name} = _decodeOption(bytes, off, (bytes, off) => _decodeList(bytes, off, ${decodeCallForType(type)}));`);
  } else if (!required) {
    lines.push(`  const ${name} = _decodeOption(bytes, off, ${decodeCallForType(type)});`);
  } else {
    lines.push(`  ${decodeDirectCallForType(type, name)}`);
  }
}
