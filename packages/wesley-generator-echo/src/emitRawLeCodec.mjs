/**
 * Emit encode/decode impl for an ENUM type.
 * Variants are sorted alphabetically; index is u32 LE.
 */
function emitEnumCodec(w, type) {
  const sorted = [...type.values].sort((a, b) => a.localeCompare(b));

  // encode
  w.writeLine(`impl ${type.name} {`);
  w.indent();
  w.writeLine('pub fn encode_raw_le(&self) -> Vec<u8> {');
  w.indent();
  w.writeLine('let idx: u32 = match self {');
  w.indent();
  sorted.forEach((v, i) => {
    w.writeLine(`Self::${v} => ${i},`);
  });
  w.dedent();
  w.writeLine('};');
  w.writeLine('idx.to_le_bytes().to_vec()');
  w.dedent();
  w.writeLine('}');
  w.writeLine();

  // decode
  w.writeLine('pub fn decode_raw_le(bytes: &[u8], offset: &mut usize) -> Result<Self, DecodeError> {');
  w.indent();
  w.writeLine('if *offset + 4 > bytes.len() { return Err(DecodeError::UnexpectedEof); }');
  w.writeLine('let idx = u32::from_le_bytes([bytes[*offset], bytes[*offset + 1], bytes[*offset + 2], bytes[*offset + 3]]);');
  w.writeLine('*offset += 4;');
  w.writeLine('match idx {');
  w.indent();
  sorted.forEach((v, i) => {
    w.writeLine(`${i} => Ok(Self::${v}),`);
  });
  w.writeLine('v => Err(DecodeError::InvalidEnumVariant(v)),');
  w.dedent();
  w.writeLine('}');
  w.dedent();
  w.writeLine('}');

  w.dedent();
  w.writeLine('}');
  w.writeLine();
}

/**
 * Emit encode/decode impl for an OBJECT type.
 * Fields are sorted alphabetically.
 */
function emitObjectCodec(w, type) {
  const fields = [...(type.fields ?? [])].sort((a, b) => a.name.localeCompare(b.name));

  w.writeLine(`impl ${type.name} {`);
  w.indent();

  // encode
  w.writeLine('pub fn encode_raw_le(&self) -> Vec<u8> {');
  w.indent();
  w.writeLine('let mut buf = Vec::new();');

  for (const field of fields) {
    const snake = toSnakeCase(field.name);
    emitFieldEncode(w, field, snake);
  }

  w.writeLine('buf');
  w.dedent();
  w.writeLine('}');
  w.writeLine();

  // decode
  w.writeLine('pub fn decode_raw_le(bytes: &[u8]) -> Result<Self, DecodeError> {');
  w.indent();
  w.writeLine('let mut offset = 0;');

  for (const field of fields) {
    const snake = toSnakeCase(field.name);
    emitFieldDecode(w, field, snake);
  }

  w.writeLine('Ok(Self {');
  w.indent();
  for (const field of fields) {
    const snake = toSnakeCase(field.name);
    w.writeLine(`${snake},`);
  }
  w.dedent();
  w.writeLine('})');
  w.dedent();
  w.writeLine('}');

  w.dedent();
  w.writeLine('}');
  w.writeLine();
}

// ---------------------------------------------------------------------------
// Field-level encode/decode emission
// ---------------------------------------------------------------------------

const SCALAR_TYPES = new Set(['Boolean', 'Int', 'Float', 'String', 'ID']);

function isScalar(typeName) {
  return SCALAR_TYPES.has(typeName);
}

function encodeExprForScalar(typeName, accessor) {
  switch (typeName) {
    case 'Boolean':
      return `buf.push(encode_bool(${accessor}));`;
    case 'Int':
      return `buf.extend_from_slice(&encode_i32_le(${accessor}));`;
    case 'Float':
      return `buf.extend_from_slice(&encode_f32_le(${accessor}));`;
    case 'String':
    case 'ID':
      return `buf.extend(encode_string(&${accessor}));`;
    default:
      // nested object / enum — call its encode_raw_le
      return `buf.extend(${accessor}.encode_raw_le());`;
  }
}

function encodeClosureForType(typeName) {
  switch (typeName) {
    case 'Boolean':
      return '|v| vec![encode_bool(*v)]';
    case 'Int':
      return '|v| encode_i32_le(*v).to_vec()';
    case 'Float':
      return '|v| encode_f32_le(*v).to_vec()';
    case 'String':
    case 'ID':
      return '|v| encode_string(v)';
    default:
      return '|v| v.encode_raw_le()';
  }
}

function decodeCallForType(typeName) {
  switch (typeName) {
    case 'Boolean':
      return 'decode_bool(bytes, &mut offset)?';
    case 'Int':
      return 'decode_i32_le(bytes, &mut offset)?';
    case 'Float':
      return 'decode_f32_le(bytes, &mut offset)?';
    case 'String':
    case 'ID':
      return 'decode_string(bytes, &mut offset)?';
    default:
      return `${typeName}::decode_raw_le_at(bytes, &mut offset)?`;
  }
}

function decodeClosureForType(typeName) {
  switch (typeName) {
    case 'Boolean':
      return 'decode_bool';
    case 'Int':
      return 'decode_i32_le';
    case 'Float':
      return 'decode_f32_le';
    case 'String':
    case 'ID':
      return 'decode_string';
    default:
      return `${typeName}::decode_raw_le_at`;
  }
}

function emitFieldEncode(w, field, snake) {
  const { type, required, list } = field;

  if (list && required) {
    // Required list: &[T]
    w.writeLine(`buf.extend(encode_list(&self.${snake}, ${encodeClosureForType(type)}));`);
  } else if (list && !required) {
    // Optional list: Option<Vec<T>>
    w.writeLine(`buf.extend(encode_option(&self.${snake}, |inner| encode_list(inner, ${encodeClosureForType(type)})));`);
  } else if (!required) {
    // Optional scalar/object
    w.writeLine(`buf.extend(encode_option(&self.${snake}, ${encodeClosureForType(type)}));`);
  } else {
    // Required scalar/object
    w.writeLine(encodeExprForScalar(type, `self.${snake}`));
  }
}

function emitFieldDecode(w, field, snake) {
  const { type, required, list } = field;

  if (list && required) {
    w.writeLine(`let ${snake} = decode_list(bytes, &mut offset, ${decodeClosureForType(type)})?;`);
  } else if (list && !required) {
    w.writeLine(`let ${snake} = decode_option(bytes, &mut offset, |b, o| decode_list(b, o, ${decodeClosureForType(type)}))?;`);
  } else if (!required) {
    w.writeLine(`let ${snake} = decode_option(bytes, &mut offset, ${decodeClosureForType(type)})?;`);
  } else {
    w.writeLine(`let ${snake} = ${decodeCallForType(type)};`);
  }
}

/**
 * Convert a camelCase name to snake_case.
 * @param {string} name
 * @returns {string}
 */
function toSnakeCase(name) {
  return name.replace(/([A-Z])/g, '_$1').toLowerCase().replace(/^_/, '');
}
