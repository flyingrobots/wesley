import { RustWriter } from './rust-writer.mjs';

/**
 * Emit a Rust `raw_le_codec.generated.rs` file containing deterministic
 * encode/decode functions for every OBJECT and ENUM type in the IR.
 *
 * Layout follows SPEC-0008:
 * - Fields encoded in alphabetical order
 * - Little-endian byte order for all numerics
 * - Collision-free Option<T> prefix (0x00 = None, 0x01 = Some)
 * - NaN canonicalization for f32
 *
 * Returns `null` when the IR contains no OBJECT or ENUM types.
 *
 * @param {{ types: Array<{ name: string, kind: string, fields?: Array<{ name: string, type: string, required: boolean, list: boolean }>, values?: string[] }> }} ir
 * @returns {string | null}
 */
export function emitRawLeCodec(ir) {
  const encodableTypes = (ir.types ?? []).filter(
    (t) => t.kind === 'OBJECT' || t.kind === 'ENUM',
  );

  if (encodableTypes.length === 0) return null;

  const w = new RustWriter();

  w.writeLine('// Auto-generated by @wesley/generator-echo — DO NOT EDIT');
  w.writeLine('#![forbid(unsafe_code)]');
  w.writeLine();

  // DecodeError
  emitDecodeError(w);

  // Shared helpers
  emitHelpers(w);

  // Per-type impls
  for (const type of encodableTypes) {
    if (type.kind === 'ENUM') {
      emitEnumCodec(w, type);
    } else if (type.kind === 'OBJECT') {
      emitObjectCodec(w, type);
    }
  }

  return w.toString();
}

/**
 * Emit the `DecodeError` enum.
 */
function emitDecodeError(w) {
  w.writeLine('#[derive(Debug, Clone, PartialEq)]');
  w.writeLine('pub enum DecodeError {');
  w.indent();
  w.writeLine('UnexpectedEof,');
  w.writeLine('InvalidOptionTag(u8),');
  w.writeLine('InvalidEnumVariant(u32),');
  w.writeLine('Utf8Error(std::string::FromUtf8Error),');
  w.dedent();
  w.writeLine('}');
  w.writeLine();

  w.writeLine('impl std::fmt::Display for DecodeError {');
  w.indent();
  w.writeLine('fn fmt(&self, f: &mut std::fmt::Formatter<\'_>) -> std::fmt::Result {');
  w.indent();
  w.writeLine('match self {');
  w.indent();
  w.writeLine('DecodeError::UnexpectedEof => write!(f, "unexpected end of input"),');
  w.writeLine('DecodeError::InvalidOptionTag(t) => write!(f, "invalid option tag: {}", t),');
  w.writeLine('DecodeError::InvalidEnumVariant(v) => write!(f, "invalid enum variant: {}", v),');
  w.writeLine('DecodeError::Utf8Error(e) => write!(f, "utf8 error: {}", e),');
  w.dedent();
  w.writeLine('}');
  w.dedent();
  w.writeLine('}');
  w.dedent();
  w.writeLine('}');
  w.writeLine();
}

/**
 * Emit shared helper functions for encoding/decoding primitives.
 */
function emitHelpers(w) {
  // encode helpers
  w.writeLine('fn encode_bool(v: bool) -> u8 {');
  w.indent();
  w.writeLine('if v { 0x01 } else { 0x00 }');
  w.dedent();
  w.writeLine('}');
  w.writeLine();

  w.writeLine('fn encode_i32_le(v: i32) -> [u8; 4] {');
  w.indent();
  w.writeLine('v.to_le_bytes()');
  w.dedent();
  w.writeLine('}');
  w.writeLine();

  w.writeLine('fn encode_f32_le(v: f32) -> [u8; 4] {');
  w.indent();
  w.writeLine('let v = if v.is_nan() { f32::from_bits(0x7FC00000) } else { v };');
  w.writeLine('v.to_le_bytes()');
  w.dedent();
  w.writeLine('}');
  w.writeLine();

  w.writeLine('fn encode_string(s: &str) -> Vec<u8> {');
  w.indent();
  w.writeLine('let bytes = s.as_bytes();');
  w.writeLine('let mut buf = Vec::with_capacity(4 + bytes.len());');
  w.writeLine('buf.extend_from_slice(&(bytes.len() as u32).to_le_bytes());');
  w.writeLine('buf.extend_from_slice(bytes);');
  w.writeLine('buf');
  w.dedent();
  w.writeLine('}');
  w.writeLine();

  w.writeLine('fn encode_option<T, F>(v: &Option<T>, encode_inner: F) -> Vec<u8>');
  w.writeLine('where');
  w.indent();
  w.writeLine('F: Fn(&T) -> Vec<u8>,');
  w.dedent();
  w.writeLine('{');
  w.indent();
  w.writeLine('match v {');
  w.indent();
  w.writeLine('None => vec![0x00],');
  w.writeLine('Some(inner) => {');
  w.indent();
  w.writeLine('let mut buf = vec![0x01];');
  w.writeLine('buf.extend(encode_inner(inner));');
  w.writeLine('buf');
  w.dedent();
  w.writeLine('}');
  w.dedent();
  w.writeLine('}');
  w.dedent();
  w.writeLine('}');
  w.writeLine();

  w.writeLine('fn encode_list<T, F>(v: &[T], encode_inner: F) -> Vec<u8>');
  w.writeLine('where');
  w.indent();
  w.writeLine('F: Fn(&T) -> Vec<u8>,');
  w.dedent();
  w.writeLine('{');
  w.indent();
  w.writeLine('let mut buf = Vec::new();');
  w.writeLine('buf.extend_from_slice(&(v.len() as u32).to_le_bytes());');
  w.writeLine('for item in v {');
  w.indent();
  w.writeLine('buf.extend(encode_inner(item));');
  w.dedent();
  w.writeLine('}');
  w.writeLine('buf');
  w.dedent();
  w.writeLine('}');
  w.writeLine();

  // decode helpers
  w.writeLine('fn decode_bool(bytes: &[u8], offset: &mut usize) -> Result<bool, DecodeError> {');
  w.indent();
  w.writeLine('if *offset >= bytes.len() { return Err(DecodeError::UnexpectedEof); }');
  w.writeLine('let v = bytes[*offset] != 0x00;');
  w.writeLine('*offset += 1;');
  w.writeLine('Ok(v)');
  w.dedent();
  w.writeLine('}');
  w.writeLine();

  w.writeLine('fn decode_i32_le(bytes: &[u8], offset: &mut usize) -> Result<i32, DecodeError> {');
  w.indent();
  w.writeLine('if *offset + 4 > bytes.len() { return Err(DecodeError::UnexpectedEof); }');
  w.writeLine('let v = i32::from_le_bytes([bytes[*offset], bytes[*offset + 1], bytes[*offset + 2], bytes[*offset + 3]]);');
  w.writeLine('*offset += 4;');
  w.writeLine('Ok(v)');
  w.dedent();
  w.writeLine('}');
  w.writeLine();

  w.writeLine('fn decode_f32_le(bytes: &[u8], offset: &mut usize) -> Result<f32, DecodeError> {');
  w.indent();
  w.writeLine('if *offset + 4 > bytes.len() { return Err(DecodeError::UnexpectedEof); }');
  w.writeLine('let v = f32::from_le_bytes([bytes[*offset], bytes[*offset + 1], bytes[*offset + 2], bytes[*offset + 3]]);');
  w.writeLine('*offset += 4;');
  w.writeLine('Ok(v)');
  w.dedent();
  w.writeLine('}');
  w.writeLine();

  w.writeLine('fn decode_string(bytes: &[u8], offset: &mut usize) -> Result<String, DecodeError> {');
  w.indent();
  w.writeLine('if *offset + 4 > bytes.len() { return Err(DecodeError::UnexpectedEof); }');
  w.writeLine('let len = u32::from_le_bytes([bytes[*offset], bytes[*offset + 1], bytes[*offset + 2], bytes[*offset + 3]]) as usize;');
  w.writeLine('*offset += 4;');
  w.writeLine('if *offset + len > bytes.len() { return Err(DecodeError::UnexpectedEof); }');
  w.writeLine('let v = String::from_utf8(bytes[*offset..*offset + len].to_vec()).map_err(DecodeError::Utf8Error)?;');
  w.writeLine('*offset += len;');
  w.writeLine('Ok(v)');
  w.dedent();
  w.writeLine('}');
  w.writeLine();

  w.writeLine('fn decode_option<T, F>(bytes: &[u8], offset: &mut usize, decode_inner: F) -> Result<Option<T>, DecodeError>');
  w.writeLine('where');
  w.indent();
  w.writeLine('F: Fn(&[u8], &mut usize) -> Result<T, DecodeError>,');
  w.dedent();
  w.writeLine('{');
  w.indent();
  w.writeLine('if *offset >= bytes.len() { return Err(DecodeError::UnexpectedEof); }');
  w.writeLine('let tag = bytes[*offset];');
  w.writeLine('*offset += 1;');
  w.writeLine('match tag {');
  w.indent();
  w.writeLine('0x00 => Ok(None),');
  w.writeLine('0x01 => Ok(Some(decode_inner(bytes, offset)?)),');
  w.writeLine('t => Err(DecodeError::InvalidOptionTag(t)),');
  w.dedent();
  w.writeLine('}');
  w.dedent();
  w.writeLine('}');
  w.writeLine();

  w.writeLine('fn decode_list<T, F>(bytes: &[u8], offset: &mut usize, decode_inner: F) -> Result<Vec<T>, DecodeError>');
  w.writeLine('where');
  w.indent();
  w.writeLine('F: Fn(&[u8], &mut usize) -> Result<T, DecodeError>,');
  w.dedent();
  w.writeLine('{');
  w.indent();
  w.writeLine('if *offset + 4 > bytes.len() { return Err(DecodeError::UnexpectedEof); }');
  w.writeLine('let count = u32::from_le_bytes([bytes[*offset], bytes[*offset + 1], bytes[*offset + 2], bytes[*offset + 3]]) as usize;');
  w.writeLine('*offset += 4;');
  w.writeLine('let mut items = Vec::with_capacity(count);');
  w.writeLine('for _ in 0..count {');
  w.indent();
  w.writeLine('items.push(decode_inner(bytes, offset)?);');
  w.dedent();
  w.writeLine('}');
  w.writeLine('Ok(items)');
  w.dedent();
  w.writeLine('}');
  w.writeLine();
}

