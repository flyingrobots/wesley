/**
 * Rust Registry Generator
 *
 * Generates registry lookup tables for TTD types and operations.
 */

/**
 * Generate Rust registry code from TTD schema
 */
export function generateRustRegistry(schema) {
  const lines = [];

  lines.push('//! TTD Registry Tables');
  lines.push('//!');
  lines.push('//! Auto-generated by @wesley/generator-ttd');
  lines.push('');
  lines.push('use std::collections::HashMap;');
  lines.push('use once_cell::sync::Lazy;');
  lines.push('');

  // Type registry
  lines.push('/// Type name to ID mapping');
  lines.push('pub static TYPE_REGISTRY: Lazy<HashMap<&\'static str, u32>> = Lazy::new(|| {');
  lines.push('    let mut m = HashMap::new();');

  for (const entry of schema.registry || []) {
    lines.push(`    m.insert("${entry.typeName}", ${entry.id});`);
  }

  lines.push('    m');
  lines.push('});');
  lines.push('');

  // Reverse type registry
  lines.push('/// Type ID to name mapping');
  lines.push('pub static TYPE_REGISTRY_REV: Lazy<HashMap<u32, &\'static str>> = Lazy::new(|| {');
  lines.push('    let mut m = HashMap::new();');

  for (const entry of schema.registry || []) {
    lines.push(`    m.insert(${entry.id}, "${entry.typeName}");`);
  }

  lines.push('    m');
  lines.push('});');
  lines.push('');

  // Op registry
  lines.push('/// Operation name to ID mapping');
  lines.push('pub static OP_REGISTRY: Lazy<HashMap<&\'static str, u32>> = Lazy::new(|| {');
  lines.push('    let mut m = HashMap::new();');

  for (const op of schema.ops || []) {
    lines.push(`    m.insert("${op.name}", ${op.op_id});`);
  }

  lines.push('    m');
  lines.push('});');
  lines.push('');

  // Reverse op registry
  lines.push('/// Operation ID to name mapping');
  lines.push('pub static OP_REGISTRY_REV: Lazy<HashMap<u32, &\'static str>> = Lazy::new(|| {');
  lines.push('    let mut m = HashMap::new();');

  for (const op of schema.ops || []) {
    lines.push(`    m.insert(${op.op_id}, "${op.name}");`);
  }

  lines.push('    m');
  lines.push('});');
  lines.push('');

  // Lookup functions
  lines.push('/// Get type ID for a type name');
  lines.push('pub fn type_id_for_name(name: &str) -> Option<u32> {');
  lines.push('    TYPE_REGISTRY.get(name).copied()');
  lines.push('}');
  lines.push('');

  lines.push('/// Get type name for a type ID');
  lines.push('pub fn type_name_for_id(id: u32) -> Option<&\'static str> {');
  lines.push('    TYPE_REGISTRY_REV.get(&id).copied()');
  lines.push('}');
  lines.push('');

  lines.push('/// Get operation ID for an operation name');
  lines.push('pub fn op_id_for_name(name: &str) -> Option<u32> {');
  lines.push('    OP_REGISTRY.get(name).copied()');
  lines.push('}');
  lines.push('');

  lines.push('/// Get operation name for an operation ID');
  lines.push('pub fn op_name_for_id(id: u32) -> Option<&\'static str> {');
  lines.push('    OP_REGISTRY_REV.get(&id).copied()');
  lines.push('}');

  return lines.join('\n');
}
